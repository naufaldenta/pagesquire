import { readFile } from 'node:fs/promises';
import { ProjectFiles, json, OnboardingError } from './files.js';
import { CONFIG, SCAN, REPORT, defaultConfig, loadConfig } from './config.js';
import { loadFreshScan } from './scan.js';

export async function initialize(files: ProjectFiles, url?: string) {
  const config = defaultConfig(url);
  await files.create({
    [CONFIG]: json(config),
    [config.manifest]: json({ schemaVersion: '0.1', capabilities: [] }),
    [config.bindings]: json({
      schemaVersion: '0.1',
      handlers: {},
      verifiers: {},
    }),
    'pagesquire/adapter.mjs':
      '// Site-owned handlers and postcondition verifiers belong here. No capabilities are enabled by default.\nexport {};\n',
  });
  return {
    initialized: true,
    enabledCapabilities: 0,
    next: 'Run pagesquire scan, then pagesquire report. No application code or dependencies were changed.',
  };
}
export async function writeReport(files: ProjectFiles) {
  const scan = await loadFreshScan(files);
  const config = await loadConfig(files);
  const observed = scan.dom.filter((page) => page.status === 'observed');
  const unvisited = config.site.paths.filter(
    (page) => !observed.some((visit) => visit.path === page),
  );
  const ambiguous = observed.reduce(
    (count, page) =>
      count + page.controls.filter((control) => control.matches > 1).length,
    0,
  );
  const markdown = `<!-- Generated by PageSquire 0.1 -->\n# PageSquire discovery report\n\nDiscovery is not authorization, training, or runtime verification.\n\n- Source files: ${scan.files.length}\n- Static candidates: ${scan.candidates.length}\n- Source scan truncated: ${scan.coverage.truncated}\n- Skipped entries: ${scan.coverage.skipped}\n- Explicit pages observed: ${observed.length}\n- Configured pages not observed: ${unvisited.length}\n- Ambiguous DOM selector hints: ${ambiguous}\n- Blocked browser requests: ${scan.dom.reduce((count, page) => count + page.blockedRequests, 0)}\n- Runtime verified: false\n\n## Required review\n\nInspect the local scan JSON for file/line metadata. Review ambiguous hints and hidden, authenticated, database-generated, dynamically loaded, and unvisited states. Scripts and foreign resources may be blocked during DOM scanning; failed or truncated pages are incomplete coverage. No candidate becomes a capability automatically. A static pass cannot prove adapter behavior.\n\n## Continue\n\nManual: implement reviewed capabilities, named handler/verifier exports and binding inventory, then run pagesquire validate --compile and host browser tests.\n\nAI-assisted: run pagesquire prepare-ai --host codex (or claude/both), review the generated skill, and invoke $assistant-setup in Codex or /assistant-setup in Claude Code. No external AI is contacted by this CLI.\n`;
  await files.artifact(REPORT, markdown, (old) =>
    old.startsWith('<!-- Generated by PageSquire 0.1 -->'),
  );
  return {
    report: REPORT,
    staticCandidates: scan.candidates.length,
    observedPages: observed.length,
    unvisitedPages: unvisited.length,
    ambiguousHints: ambiguous,
    runtimeVerified: false,
  };
}
export async function prepareAi(files: ProjectFiles, host: string) {
  if (!['codex', 'claude', 'both'].includes(host))
    throw new OnboardingError(
      'INVALID_HOST',
      'Select --host codex, claude, or both.',
    );
  const scan = await loadFreshScan(files);
  const config = await loadConfig(files);
  const artifacts: Record<string, string> = {};
  const template = new URL('./templates/assistant-setup/', import.meta.url);
  const manifest = await readFile(new URL('SKILL.md', template), 'utf8');
  const integration = await readFile(
    new URL('references/integration.md', template),
    'utf8',
  );
  const metadata = await readFile(
    new URL('agents/openai.yaml', template),
    'utf8',
  );
  const project = json({
    format: 'pagesquire-ai-context',
    version: '0.1',
    untrustedEvidence: true,
    config: CONFIG,
    scan: SCAN,
    report: REPORT,
    manifest: config.manifest,
    bindings: config.bindings,
    generated: config.generated,
    sourceFiles: scan.files.length,
    runtimeVerified: false,
  });
  const hosts = host === 'both' ? ['codex', 'claude'] : [host];
  for (const selected of hosts) {
    const legacy =
      selected === 'codex'
        ? '.codex/skills/assistant-setup/SKILL.md'
        : '.claude/commands/assistant-setup.md';
    if (await files.exists(legacy))
      throw new OnboardingError(
        'SKILL_CONFLICT',
        'An existing assistant-setup integration exists. Review it before installing a project skill.',
      );
  }
  for (const selected of hosts) {
    const directory =
      selected === 'codex'
        ? '.agents/skills/assistant-setup'
        : '.claude/skills/assistant-setup';
    artifacts[`${directory}/SKILL.md`] = manifest;
    artifacts[`${directory}/references/integration.md`] = integration;
    artifacts[`${directory}/references/project.json`] = project;
    if (selected === 'codex')
      artifacts[`${directory}/agents/openai.yaml`] = metadata;
  }
  await files.create(artifacts);
  return {
    prepared: true,
    hosts,
    files: Object.keys(artifacts),
    invocations: hosts.map((selected) =>
      selected === 'codex' ? '$assistant-setup' : '/assistant-setup',
    ),
    externalAiContacted: false,
    runtimeVerified: false,
  };
}
