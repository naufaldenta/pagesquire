import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from '@babel/parser';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneModule from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { validateManifest } from '@pagesquire/protocol';
import type { CapabilityManifest } from '@pagesquire/protocol';
import { ProjectFiles, OnboardingError, excludedPath } from './files.js';
import { loadConfig } from './config.js';

interface Binding {
  module: string;
  export: string;
}
interface Inventory {
  schemaVersion: '0.1';
  handlers: Record<string, Binding>;
  verifiers: Record<string, Binding>;
}
export interface ValidationReport {
  valid: boolean;
  scope: 'static-contract';
  runtimeVerified: false;
  capabilityCount: number;
  errors: string[];
  warnings: string[];
  compiled: boolean;
}
export const GENERATED = '// Generated by PageSquire 0.1. Do not edit.\n';
const standaloneCode = standaloneModule as unknown as (
  ajv: Ajv2020,
  refs: Record<string, string>,
) => string;
const bindingSchema = {
  type: 'object',
  additionalProperties: false,
  required: ['module', 'export'],
  properties: {
    module: { type: 'string', maxLength: 240 },
    export: { type: 'string', pattern: '^[A-Za-z_$][A-Za-z0-9_$]{0,127}$' },
  },
};
const inventorySchema = {
  type: 'object',
  additionalProperties: false,
  required: ['schemaVersion', 'handlers', 'verifiers'],
  properties: {
    schemaVersion: { const: '0.1' },
    handlers: {
      type: 'object',
      maxProperties: 100,
      additionalProperties: bindingSchema,
    },
    verifiers: {
      type: 'object',
      maxProperties: 100,
      additionalProperties: bindingSchema,
    },
  },
};

function exportedFunctions(source: string, name: string): Set<string> {
  const ast = parse(source, {
    sourceType: 'module',
    plugins: [
      ...(/\.tsx?$/.test(name) ? ['typescript' as const] : []),
      ...(/\.[jt]sx$/.test(name) ? ['jsx' as const] : []),
    ],
  });
  const result = new Set<string>();
  for (const statement of ast.program.body) {
    if (statement.type !== 'ExportNamedDeclaration' || !statement.declaration)
      continue;
    const node = statement.declaration;
    if (node.type === 'FunctionDeclaration' && node.id && node.body)
      result.add(node.id.name);
    if (node.type === 'VariableDeclaration')
      for (const variable of node.declarations) {
        if (
          variable.id.type === 'Identifier' &&
          variable.init &&
          ['ArrowFunctionExpression', 'FunctionExpression'].includes(
            variable.init.type,
          )
        )
          result.add(variable.id.name);
      }
  }
  return result;
}
function checkSchema(value: unknown, depth = 0): void {
  if (depth > 20)
    throw new OnboardingError(
      'UNSUPPORTED_SCHEMA',
      'Parameter schemas must have bounded nesting.',
    );
  if (Array.isArray(value)) {
    for (const item of value) checkSchema(item, depth + 1);
  } else if (value && typeof value === 'object')
    for (const [key, child] of Object.entries(value)) {
      if (['$ref', '$dynamicRef', '$async', '$data'].includes(key))
        throw new OnboardingError(
          'UNSUPPORTED_SCHEMA',
          'F3 parameter schemas must be self-contained and synchronous.',
        );
      checkSchema(child, depth + 1);
    }
}
export async function validateProject(
  files: ProjectFiles,
  compile = false,
): Promise<ValidationReport> {
  const config = await loadConfig(files);
  const report: ValidationReport = {
    valid: false,
    scope: 'static-contract',
    runtimeVerified: false,
    capabilityCount: 0,
    errors: [],
    warnings: [
      'Static validation does not execute adapters or verify browser postconditions. Run host/browser tests before enabling capabilities.',
    ],
    compiled: false,
  };
  const manifest = await files.readJson(config.manifest, 262144);
  const validation = validateManifest(manifest);
  if (!validation.valid) {
    report.errors.push('INVALID_MANIFEST');
    return report;
  }
  const catalog: CapabilityManifest = validation.value;
  report.capabilityCount = catalog.capabilities.length;
  if (!catalog.capabilities.length) report.errors.push('EMPTY_MANIFEST');
  if (catalog.capabilities.length > 100) report.errors.push('CAPABILITY_LIMIT');
  if (
    new Set(catalog.capabilities.map((capability) => capability.id)).size !==
    catalog.capabilities.length
  )
    report.errors.push('DUPLICATE_CAPABILITY');
  if (
    catalog.capabilities.some(
      (capability) => capability.risk === 'consequential',
    )
  )
    report.errors.push('CONSEQUENTIAL_DISABLED');
  const inventory = await files.readJson(config.bindings);
  const ajv = new Ajv2020({
    strict: true,
    ownProperties: true,
    code: { source: true, esm: true },
  });
  if (!ajv.validate(inventorySchema, inventory)) {
    report.errors.push('INVALID_BINDINGS');
    return report;
  }
  const bindings = inventory as Inventory;
  const modules = new Map<string, Set<string>>();
  const imports: string[] = [];
  const mappings: { handlers: string[]; verifiers: string[] } = {
    handlers: [],
    verifiers: [],
  };
  for (const kind of ['handlers', 'verifiers'] as const) {
    const required = new Set(
      catalog.capabilities.map((capability) =>
        kind === 'handlers'
          ? capability.handler
          : capability.verification.handler,
      ),
    );
    for (const id of required) {
      const binding = Object.hasOwn(bindings[kind], id)
        ? bindings[kind][id]
        : undefined;
      if (!binding) {
        report.errors.push(`MISSING_${kind.toUpperCase()}:${id}`);
        continue;
      }
      const inspectedPath = binding.module.startsWith('pagesquire/')
        ? binding.module.slice('pagesquire/'.length)
        : binding.module;
      if (
        !/\.(?:[cm]?js|tsx?)$/.test(binding.module) ||
        excludedPath(inspectedPath)
      ) {
        report.errors.push(`UNSAFE_MODULE:${id}`);
        continue;
      }
      await files.resolve(binding.module);
      if (!modules.has(binding.module))
        modules.set(
          binding.module,
          exportedFunctions(
            await files.read(binding.module, 262144),
            binding.module,
          ),
        );
      if (!modules.get(binding.module)!.has(binding.export)) {
        report.errors.push(`MISSING_EXPORT:${id}`);
        continue;
      }
      const alias = `binding${imports.length}`;
      const relative = path.posix.relative(config.generated, binding.module);
      imports.push(
        `import { ${binding.export} as ${alias} } from ${JSON.stringify(relative.startsWith('.') ? relative : `./${relative}`)};`,
      );
      mappings[kind].push(`[${JSON.stringify(id)}]: ${alias}`);
    }
    for (const id of Object.keys(bindings[kind]))
      if (!required.has(id))
        report.warnings.push(`UNUSED_${kind.toUpperCase()}:${id}`);
  }
  const exports: Record<string, string> = {};
  const parameters: string[] = [];
  for (const [index, capability] of catalog.capabilities.entries()) {
    try {
      checkSchema(capability.inputSchema);
      const id = `urn:pagesquire:onboarding:${index}`;
      ajv.addSchema({ ...capability.inputSchema, $id: id });
      ajv.getSchema(id);
      exports[`p${index}`] = id;
      parameters.push(
        `[${JSON.stringify(capability.id)}]: { schema: ${JSON.stringify(capability.inputSchema)}, validate: p${index} }`,
      );
    } catch {
      report.errors.push(`INVALID_PARAMETER_SCHEMA:${capability.id}`);
    }
  }
  report.valid = report.errors.length === 0;
  if (!compile || !report.valid) return report;
  const names = [
    `${config.generated}/parameters.js`,
    `${config.generated}/bindings.mjs`,
  ];
  for (const name of names) {
    await files.resolve(name);
    if (
      (await files.exists(name)) &&
      !(await files.read(name, 2_000_000)).startsWith(GENERATED)
    )
      throw new OnboardingError(
        'FILE_CONFLICT',
        'Refusing to overwrite a hand-written generated target.',
      );
  }
  const code = standaloneCode(ajv, exports);
  const output = await build({
    stdin: {
      contents: code,
      resolveDir: path.dirname(fileURLToPath(import.meta.url)),
      loader: 'js',
    },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    legalComments: 'inline',
  });
  const artifact = output.outputFiles[0]!.text;
  await files.artifact(
    names[0]!,
    `${GENERATED}${artifact}\nexport const parameters = { ${parameters.join(',\n')} };\n`,
    (old) => old.startsWith(GENERATED),
  );
  await files.artifact(
    names[1]!,
    `${GENERATED}${imports.join('\n')}\nexport const handlers = { ${mappings.handlers.join(',\n')} };\nexport const verifiers = { ${mappings.verifiers.join(',\n')} };\n`,
    (old) => old.startsWith(GENERATED),
  );
  report.compiled = true;
  return report;
}
